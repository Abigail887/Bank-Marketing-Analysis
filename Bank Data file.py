# We are loading our CSV file into a dataframe called df
# A dataframe is like an Excel spreadsheet inside Python
# Make sure you have uploaded bank-full.csv to your Colab session first

df = pd.read_csv('bank-full.csv', sep=';')
# sep=';' tells Python that the columns in this file are separated by semicolons

print("Dataset loaded successfully!")
print(f"Rows: {df.shape[0]}")      # how many customers are in the dataset
print(f"Columns: {df.shape[1]}")   # how many pieces of information we have per customer

# Let's look at the first 5 rows to understand what our data looks like
df.head()

# This checks if any column has missing values
