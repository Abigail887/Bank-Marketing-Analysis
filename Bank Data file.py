# value_counts() counts each unique value in the y column

subscription_counts = df['y'].value_counts()
# normalize=True converts the counts into percentages
subscription_percent = df['y'].value_counts(normalize=True) * 100

print("Subscription Counts:")
print(subscription_counts)
print("\nSubscription Percentage:")
print(subscription_percent.round(1))

# Now let us visualize the yes vs no split as a pie chart and a bar chart side by side

fig, axes = plt.subplots(1, 2, figsize=(12, 5))
# fig is our canvas, axes are the two chart areas
# 1, 2 means 1 row and 2 columns — so two charts side by side

# ── Left Chart: Pie Chart ──
axes[0].pie(
    subscription_counts,                        # the values to plot
    labels=['Did Not Subscribe', 'Subscribed'], # labels for each slice
    colors=['#E74C3C', '#2ECC71'],              # red for no, green for yes
    autopct='%1.1f%%',                          # show percentage on each slice
    startangle=90,                              # start the pie from the top
    textprops={'fontsize': 11}
)
axes[0].set_title('Overall Subscription Split', fontsize=13, fontweight='bold', color='#1F4E79')

# ── Right Chart: Bar Chart ──
bars = axes[1].bar(
    ['Did Not Subscribe', 'Subscribed'],        # labels on x axis
    subscription_counts.values,                 # the count values
    color=['#E74C3C', '#2ECC71'],               # red for no, green for yes
    edgecolor='white',                          # white border on each bar
    width=0.5                                   # width of each bar
)

# Add the number on top of each bar so it is easy to read
for bar in bars:
    height = bar.get_height()                   # get the height of each bar
    axes[1].text(
        bar.get_x() + bar.get_width() / 2,     # position in the middle of the bar
        height + 200,                           # just above the bar
        f'{int(height):,}',                    # the count formatted with comma
        ha='center', fontsize=11, fontweight='bold', color='#1F4E79'
    )

axes[1].set_title('Subscription Count', fontsize=13, fontweight='bold', color='#1F4E79')
axes[1].set_ylabel('Number of Customers', fontsize=11)
axes[1].grid(axis='y', alpha=0.4)              # light horizontal grid lines

plt.suptitle('How Many Customers Subscribed?', fontsize=15, fontweight='bold', color='#1F4E79', y=1.02)
