# We want to know which job types have the highest subscription rate
# First we calculate the subscription rate per job group

job_rate = (
    df.groupby('job')['y']              # group the data by job type
    .apply(lambda x: (x == 'yes').mean() * 100)  # calculate % who said yes
    .reset_index()                       # turn the result into a clean table
    .rename(columns={'y': 'subscription_rate'})   # rename the column
    .sort_values('subscription_rate', ascending=False)  # sort highest to lowest
)

print(job_rate.round(1))               # print the table so we can see the numbers

fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# ── Left Chart: Bar chart of subscription rate by job ──
bars = axes[0].bar(
    job_rate['job'],                    # job types on x axis
    job_rate['subscription_rate'],      # subscription rate on y axis
    color='#3498DB',                    # blue bars
    edgecolor='white',
    width=0.6
)

# Add percentage label on top of each bar
for bar in bars:
    height = bar.get_height()
    axes[0].text(
        bar.get_x() + bar.get_width() / 2,
        height + 0.3,
        f'{height:.1f}%',
        ha='center', fontsize=8, fontweight='bold', color='#1F4E79'
    )

# Add a red dashed line showing the overall average
overall_avg = (df['y'] == 'yes').mean() * 100
axes[0].axhline(
    y=overall_avg,                      # draw a line at the overall average
    color='#E74C3C',
    linestyle='--',
    linewidth=1.5,
    label=f'Overall Average: {overall_avg:.1f}%'
)

axes[0].set_title('Subscription Rate by Job Type', fontsize=13, fontweight='bold', color='#1F4E79')
axes[0].set_xlabel('Job Type', fontsize=11)
axes[0].set_ylabel('Subscription Rate (%)', fontsize=11)
axes[0].tick_params(axis='x', rotation=45) # rotate job labels so they fit
axes[0].legend(fontsize=9)
axes[0].grid(axis='y', alpha=0.4)

# ── Right Chart: Histogram of age by subscription outcome ──
# A histogram shows us the distribution — where most customers fall by age

sns.histplot(
    data=df,                            # our full dataset
    x='age',                            # age on the x axis
    hue='y',                            # colour by yes or no
    bins=20,                            # split age into 20 groups
    palette={'yes': '#2ECC71', 'no': '#E74C3C'},  # green for yes, red for no
    alpha=0.7,                          # slight transparency so bars overlap nicely
    ax=axes[1]                          # draw this in the right chart area
)

axes[1].set_title('Age Distribution by Subscription Outcome', fontsize=13, fontweight='bold', color='#1F4E79')
axes[1].set_xlabel('Age', fontsize=11)
axes[1].set_ylabel('Number of Customers', fontsize=11)
axes[1].grid(axis='y', alpha=0.4)

plt.suptitle('Business Question 1: Who Subscribes by Job and Age?', fontsize=14, fontweight='bold', color='#1F4E79', y=1.02)
plt.tight_layout()
plt.savefig('Q1_job_and_age.png', dpi=150, bbox_inches='tight')
plt.show()

print("\n📊 FINDING: Students and retired customers subscribe at the highest rates.")
print("   Blue-collar and service workers are the least likely to subscribe.")

