# We are bringing in the tools we need for our analysis

import pandas as pd               # pandas helps us load and work with our data like a spreadsheet
import matplotlib.pyplot as plt   # matplotlib is what draws our charts
import seaborn as sns             # seaborn makes our charts look clean and professional
import warnings                   # this helps us hide unnecessary warning messages
warnings.filterwarnings('ignore') # turn off warnings so our output stays clean

# This sets a clean white background for all our charts
sns.set_theme(style="whitegrid")

# This sets the default size of every chart we draw
plt.rcParams['figure.figsize'] = (10, 5)

