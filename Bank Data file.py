# We want to know if longer calls lead to more subscriptions

# Calculate average and median call duration by outcome
duration_stats = df.groupby('y')['duration'].agg(['mean', 'median']).round(0)
print("Call Duration Statistics by Outcome:")
print(duration_stats)

fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# ── Left Chart: Box plot — duration by subscription outcome ──
# A box plot shows us the spread of the data — minimum, median, and maximum
df_dur = df[df['duration'] <= 2000]    # remove extreme outliers above 2000 seconds

sns.boxplot(
    data=df_dur,
    x='y',
    y='duration',
    palette={'yes': '#2ECC71', 'no': '#E74C3C'},
    width=0.4,
    ax=axes[0]
)

# Add median label on each box
for i, outcome in enumerate(['no', 'yes']):
    med = df_dur[df_dur['y'] == outcome]['duration'].median()
    axes[0].text(i, med + 20, f'Median: {med:.0f}s',
                 ha='center', fontsize=10, fontweight='bold', color='#1F4E79')

axes[0].set_title('Call Duration by Subscription Outcome', fontsize=13, fontweight='bold', color='#1F4E79')
axes[0].set_xlabel('Subscribed', fontsize=11)
axes[0].set_ylabel('Call Duration (seconds)', fontsize=11)
axes[0].grid(axis='y', alpha=0.4)

# ── Right Chart: Histogram — call duration distribution ──
sns.histplot(
    data=df_dur,
    x='duration',
    hue='y',
    bins=30,
    palette={'yes': '#2ECC71', 'no': '#E74C3C'},
    alpha=0.7,
    ax=axes[1]
)

# Add vertical median lines so it is easy to see the difference
med_yes = df[df['y'] == 'yes']['duration'].median()
med_no  = df[df['y'] == 'no']['duration'].median()

axes[1].axvline(med_yes, color='#1B5E20', linestyle='--', linewidth=2, label=f'Median Yes: {med_yes:.0f}s')
