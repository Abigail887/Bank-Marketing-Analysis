# Colour bars above average darker so they stand out
colors = ['#1F4E79' if v >= overall_avg else '#90CAF9'
          for v in month_rate['subscription_rate']]

bars = axes[0].bar(
    month_rate['month'],
    month_rate['subscription_rate'],
    color=colors,
    edgecolor='white',
    width=0.6
)

for bar in bars:
    height = bar.get_height()
    axes[0].text(
        bar.get_x() + bar.get_width() / 2,
        height + 0.3,
        f'{height:.1f}%',
        ha='center', fontsize=8, fontweight='bold', color='#1F4E79'
    )

axes[0].axhline(y=overall_avg, color='#E74C3C', linestyle='--',
                linewidth=1.5, label=f'Overall Average: {overall_avg:.1f}%')
axes[0].set_title('Subscription Rate by Month\n(Dark Blue = Above Average)', fontsize=12, fontweight='bold', color='#1F4E79')
